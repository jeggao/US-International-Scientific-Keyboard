def keysym_value(name: str) -> int | None:
    """Resolve a keysym token to its numeric value.

    Only the forms this project emits are understood: a ``dead_*`` name, a
    Latin-1 name, or the ``U<hex>`` form. ``None`` means "not one of ours".
    """
    if name in DEAD_KEYSYMS:
        return DEAD_KEYSYMS[name]
    if len(name) > 1 and name[0] == "U":
        try:
            code_point = int(name[1:], 16)
        except ValueError:
            return None
        # X11 encodes Latin-1 as itself and everything else with this offset.
        return code_point if code_point <= 0xFF else 0x01000000 + code_point
    for code_point, latin1 in LATIN1_KEYSYMS.items():
        if latin1 == name:
            return code_point
    return None
